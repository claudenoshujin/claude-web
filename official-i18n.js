// Sentences with numbers, as in the design (translateUI PAT).
const PAT = [[/^顺序 (\d+)$/, "Order $1"], [/^约 (\d+) Token$/, "~$1 tokens"]];
export function tr(zh, s) {
  if (zh || s == null) return s;
  const k = String(s).trim();
  if (k in EN) return EN[k];
  for (const [re, to] of PAT) if (re.test(k)) return k.replace(re, to);
  return s;
}
